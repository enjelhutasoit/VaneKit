import SwiftUI

/// Spacing scale on a 4-point grid.
public enum VaneSpacing {
    public static let unit: CGFloat = 4

    public static let xxs: CGFloat = unit
    public static let xs: CGFloat = unit * 2
    public static let sm: CGFloat = unit * 3
    public static let md: CGFloat = unit * 4
    public static let lg: CGFloat = unit * 6
    public static let xl: CGFloat = unit * 8
    public static let xxl: CGFloat = unit * 12
}
